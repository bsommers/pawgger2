const FALLBACK = G['?'];
const ROWS = new Map();
for (const [ch, rows] of Object.entries(G)) ROWS.set(ch, rows);

/** 7 strings of 5 chars ('#' ink, '.' empty) for a character; unknown chars map to '?'. */
export function glyphRows(ch) { return ROWS.get(ch) || FALLBACK; }

/** Characters the font defines. */
export function glyphChars() { return [...ROWS.keys()]; }

/** Width in px of `text` at integer `scale` (trailing spacing column excluded). Newlines: widest line. */
export function measureText(text, scale = 1) {
  scale = Math.max(1, Math.round(scale));
  let best = 0;
  for (const line of String(text).split('\n')) {
    const n = [...line].length;
    best = Math.max(best, n ? (n * ADVANCE - 1) * scale : 0);
  }
  return best;
}

const cache = new Map(); // `${color}|${scale}` -> { canvas, ... } atlas of all glyphs
const COLS = 16;

function getAtlas(color, scale) {
  if (typeof document === 'undefined' && typeof OffscreenCanvas === 'undefined') return null;
  const key = color + '|' + scale;
  let a = cache.get(key);
  if (a !== undefined) return a;
  a = null;
  try {
    const chars = glyphChars();
    const cw = ADVANCE * scale, ch = (GLYPH_H + 1) * scale;
    const rows = Math.ceil(chars.length / COLS);
    const W = COLS * cw, H = rows * ch;
    const canvas = typeof OffscreenCanvas !== 'undefined' ? new OffscreenCanvas(W, H) : Object.assign(document.createElement('canvas'), { width: W, height: H });
    const c = canvas.getContext('2d');
    if (c) {
      c.fillStyle = color;
      const pos = new Map();
      chars.forEach((chr, i) => {
        const ox = (i % COLS) * cw, oy = Math.floor(i / COLS) * ch;
        pos.set(chr, [ox, oy]);
        forRuns(glyphRows(chr), (x, y, w) => c.fillRect(ox + x * scale, oy + y * scale, w * scale, scale));
      });
      a = { canvas, pos, cw, ch };
    }
  } catch { a = null; }
  if (cache.size > 64) cache.clear();
  cache.set(key, a);
  return a;
}

function forRuns(rows, fn) {
  for (let y = 0; y < rows.length; y++) {
    const r = rows[y];
    for (let x = 0; x < 5;) {
      if (r[x] !== '#') { x++; continue; }
      let e = x; while (e < 5 && r[e] === '#') e++;
      fn(x, y, e - x); x = e;
    }
  }
}

function drawPass(ctx, text, x, y, scale, color, align) {
  const atlas = getAtlas(color, scale);
  const lines = String(text).split('\n');
  lines.forEach((line, li) => {
    const w = measureText(line, scale);
    let px = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? Math.round(x - w) : Math.round(x);
    const py = Math.round(y) + li * LINE_H * scale;
    if (!atlas) ctx.fillStyle = color;
    for (const chr of line) {
      if (chr !== ' ') {
        const g = ROWS.has(chr) ? chr : '?';
        if (atlas) {
          const [sx, sy] = atlas.pos.get(g);
          ctx.drawImage(atlas.canvas, sx, sy, atlas.cw, atlas.ch, px, py, atlas.cw, atlas.ch);
        } else {
          forRuns(glyphRows(g), (gx, gy, gw) => ctx.fillRect(px + gx * scale, py + gy * scale, gw * scale, scale));
        }
      }
      px += ADVANCE * scale;
    }
  });
}

/**
 * Draw text on a 2D context. Options: scale (integer >=1), color, shadow (colour or null; drawn 1*scale down-right),
 * align 'left'|'center'|'right' (x is the anchor). '\n' starts a new line.
 */
export function drawText(ctx, text, x, y, opts = {}) {
  const scale = Math.max(1, Math.round(opts.scale ?? 1));
  const color = opts.color ?? '#fff';
  const shadow = opts.shadow === undefined ? '#000' : opts.shadow;
  const align = opts.align ?? 'left';
  const t = String(text);
  if (shadow) drawPass(ctx, t, x + scale, y + scale, scale, shadow, align);
  drawPass(ctx, t, x, y, scale, color, align);
}
